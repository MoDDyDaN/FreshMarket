def seed(force: bool = False) -> None:
    """Заполняет базу ассортиментом, если она пустая (или force=True)."""
    init_db()
    session = SessionLocal()
    try:
        existing = session.query(Product).count()
        if existing and not force:
            return  # база уже заполнена — повторный сид не нужен

        if force:
            session.query(Product).delete()
            session.query(Category).delete()
            session.commit()

        # Категории
        categories = {}
        for slug, name, description, image in CATEGORIES:
            category = Category(slug=slug, name=name, description=description, image=image)
            session.add(category)
            categories[slug] = category
        session.flush()

        # Товары
        for slug, name, price, weight, desc, image, is_hit, origin, cat_slug in PRODUCTS:
            session.add(
                Product(
                    slug=slug,
                    name=name,
                    price=price,
                    weight=weight,
                    description=desc,
                    image=image,
                    is_hit=is_hit,
                    origin=origin,
                    category=categories[cat_slug],
                )
            )
        session.commit()
        print(f"Catalog seeded: {len(CATEGORIES)} categories, {len(PRODUCTS)} products.")
    finally:
        session.close()


if __name__ == "__main__":
    seed(force=True)  # ручной запуск: python seeder.py — пересоздать базу
